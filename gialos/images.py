"""Beach photo lookup.

Drop your own photo at `assets/beaches/<beach_id>.jpg` (or .jpeg/.png/.webp) and
it is used automatically. Until then the app shows the generated illustration
from `assets/beaches/placeholders/<beach_id>.svg`
(see scripts/generate_beach_placeholders.py).
"""

from pathlib import Path
from typing import Optional

ASSETS_DIR = Path(__file__).resolve().parent.parent / "assets"
WINDOW_ICON = ASSETS_DIR / "icon.ico"   # generated by scripts/generate_logo.py
PHOTO_DIR = "beaches"
PLACEHOLDER_DIR = "beaches/placeholders"
PHOTO_EXTENSIONS = ("jpg", "jpeg", "png", "webp")


def _photo_src(beach_id: str) -> Optional[str]:
    for ext in PHOTO_EXTENSIONS:
        rel = f"{PHOTO_DIR}/{beach_id}.{ext}"
        if (ASSETS_DIR / rel).exists():
            return rel
    return None


def has_photo(beach_id: str) -> bool:
    """True if a real photo was added for this beach (not just the placeholder)."""
    return _photo_src(beach_id) is not None


def beach_image_src(beach_id: str) -> str:
    """Asset path (relative to assets/) of the image to show for a beach."""
    return _photo_src(beach_id) or f"{PLACEHOLDER_DIR}/{beach_id}.svg"

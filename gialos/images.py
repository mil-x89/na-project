"""Beach photo lookup.

Drop your own photo at `assets/beaches/<beach_id>.jpg` (or .jpeg/.png/.webp) and
it is used automatically. Until then the app shows the generated illustration
from `assets/beaches/placeholders/<beach_id>.svg`
(see scripts/generate_beach_placeholders.py).

Where the photos are looked up:
- Normal run (desktop / `flet run --web`): the assets folder on disk.
- Static website (`flet publish`, e.g. GitHub Pages): the app runs inside the
  browser, where the assets folder is not on disk. The website build first runs
      python -m gialos.images --write-manifest
  which saves the list of photos to gialos/_photos.py; that list is used instead.
"""

import sys
from pathlib import Path
from typing import Optional

ASSETS_DIR = Path(__file__).resolve().parent.parent / "assets"
WINDOW_ICON = ASSETS_DIR / "icon.ico"   # generated by scripts/generate_logo.py
PHOTO_DIR = "beaches"
PLACEHOLDER_DIR = "beaches/placeholders"
PHOTO_EXTENSIONS = ("jpg", "jpeg", "png", "webp")
MANIFEST = Path(__file__).resolve().parent / "_photos.py"


def _scan_disk() -> frozenset[str]:
    folder = ASSETS_DIR / PHOTO_DIR
    return frozenset(
        f"{PHOTO_DIR}/{p.name}"
        for p in folder.iterdir()
        if p.is_file() and p.suffix.lower().lstrip(".") in PHOTO_EXTENSIONS
    )


def _load_photos() -> frozenset[str]:
    """Asset paths of all real beach photos (see module docstring)."""
    if (ASSETS_DIR / PHOTO_DIR).is_dir():
        return _scan_disk()
    try:
        from gialos._photos import PHOTOS
    except ImportError:
        return frozenset()
    return frozenset(PHOTOS)


_PHOTOS = _load_photos()


def _photo_src(beach_id: str) -> Optional[str]:
    for ext in PHOTO_EXTENSIONS:
        rel = f"{PHOTO_DIR}/{beach_id}.{ext}"
        if rel in _PHOTOS:
            return rel
    return None


def has_photo(beach_id: str) -> bool:
    """True if a real photo was added for this beach (not just the placeholder)."""
    return _photo_src(beach_id) is not None


def beach_image_src(beach_id: str) -> str:
    """Asset path (relative to assets/) of the image to show for a beach."""
    return _photo_src(beach_id) or f"{PLACEHOLDER_DIR}/{beach_id}.svg"


def write_manifest() -> None:
    """Save the current list of photos for the static website build."""
    photos = sorted(_scan_disk())
    MANIFEST.write_text(
        '"""Beach photos available in assets/. GENERATED by '
        '`python -m gialos.images --write-manifest`; do not edit."""\n\n'
        f"PHOTOS = {tuple(photos)!r}\n",
        encoding="utf-8",
    )
    print(f"Wrote {MANIFEST.name}: {len(photos)} photos")


if __name__ == "__main__" and sys.argv[1:] == ["--write-manifest"]:
    write_manifest()

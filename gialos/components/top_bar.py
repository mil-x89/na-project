"""Top bar with the gialos logo and the language toggle (every screen).

Built as a plain container (not a page-level AppBar) so the whole app, bars
included, can be placed inside the phone frame on wide screens.
"""

from typing import Callable, Optional

import flet as ft

from gialos import theme
from gialos.state import AppState

LOGO_IMAGE = "logo.svg"   # generated by scripts/generate_logo.py
TOP_BAR_HEIGHT = 64


def build_language_toggle(state: AppState, on_toggle: Callable[[], None]) -> ft.Control:
    """Pill button that switches between English and Greek."""
    return ft.Container(
        content=ft.Row(
            [
                ft.Icon(ft.Icons.TRANSLATE, color=theme.ACCENT, size=16),
                ft.Text(state.t("switch_language_short"), style=theme.LABEL, color=theme.ACCENT),
            ],
            spacing=theme.S1,
            tight=True,
        ),
        height=36,
        padding=ft.Padding.symmetric(horizontal=theme.S3),
        border_radius=18,
        bgcolor=theme.ACCENT_5,
        tooltip=state.t("switch_language"),
        ink=True,
        on_click=lambda _: on_toggle(),
    )


def build_top_bar(
    state: AppState,
    on_toggle_language: Callable[[], None],
    on_back: Optional[Callable[[], None]] = None,
) -> ft.Container:
    logo = ft.Image(
        src=LOGO_IMAGE,
        height=theme.LOGO_HEIGHT,
        fit=ft.BoxFit.CONTAIN,
        semantics_label=state.t("app_name"),
    )
    toggle = build_language_toggle(state, on_toggle_language)
    if on_back is None:
        # Logo on the left, toggle on the right.
        content = ft.Row([logo, ft.Container(expand=True), toggle])
        padding = ft.Padding.only(left=theme.S4, right=theme.S3)
    else:
        # Back arrow on the left, logo centred, toggle on the right.
        back = ft.IconButton(
            icon=ft.Icons.ARROW_BACK_IOS_NEW,
            icon_color=theme.INK,
            icon_size=20,
            tooltip=state.t("back"),
            on_click=lambda _: on_back(),
        )
        content = ft.Stack(
            [
                ft.Container(logo, alignment=ft.Alignment.CENTER),
                ft.Container(back, left=0, top=0, bottom=0, alignment=ft.Alignment.CENTER_LEFT),
                ft.Container(toggle, right=0, top=0, bottom=0, alignment=ft.Alignment.CENTER_RIGHT),
            ],
            fit=ft.StackFit.EXPAND,
        )
        padding = ft.Padding.only(left=theme.S1, right=theme.S3)
    return ft.Container(content=content, height=TOP_BAR_HEIGHT, padding=padding, bgcolor=theme.BACKGROUND)

"""Screen 3: map of Thassos (real OSM coastline) with village labels and tappable beach pins."""

from typing import TYPE_CHECKING

import flet as ft

from gialos import theme
from gialos.data import island
from gialos.data.beaches import BEACHES, get_beach
from gialos.data.forecasts import get_forecast
from gialos.images import beach_image_src, has_photo

if TYPE_CHECKING:
    from gialos.app import GialosApp

TOWN_DOT = 6
TOWN_LABEL_WIDTH = 80
PIN_SIZE = 24
MATCH_PIN_SIZE = 40
ISLAND_IMAGE = "thassos.svg"   # generated by scripts/generate_island.py


def _pin(app: "GialosApp", beach_id: str, is_match: bool) -> ft.Container:
    beach = get_beach(beach_id)
    day = get_forecast(beach_id)[app.state.preferences.day_index]
    x, y = island.project(beach.lat, beach.lon)
    size = MATCH_PIN_SIZE if is_match else PIN_SIZE
    return ft.Container(
        content=ft.Icon(ft.Icons.AUTO_AWESOME, size=20, color=theme.WHITE) if is_match else None,
        left=x - size / 2,
        top=y - size / 2,
        width=size,
        height=size,
        alignment=ft.Alignment.CENTER,
        shape=ft.BoxShape.CIRCLE,
        bgcolor=theme.ACCENT_DEEP if is_match else theme.CLARITY_COLORS[day.clarity_level],
        border=ft.Border.all(3, theme.WHITE),
        shadow=ft.BoxShadow(blur_radius=8, color=theme.SHADOW, offset=ft.Offset(0, 2)),
        tooltip=beach.name[app.state.language],
        on_click=lambda _: app.open_beach(beach_id),
    )


def _town(app: "GialosApp", town: island.Town) -> list[ft.Control]:
    """Small dot plus the village name, placed on the side given in the data."""
    x, y = island.project(town.lat, town.lon)
    dot = ft.Container(
        left=x - TOWN_DOT / 2, top=y - TOWN_DOT / 2, width=TOWN_DOT, height=TOWN_DOT,
        shape=ft.BoxShape.CIRCLE, bgcolor=theme.INK_60,
    )
    text = ft.Text(
        town.name[app.state.language], size=theme.SIZE_MAP_LABEL, weight=theme.BOLD, color=theme.INK_80,
        no_wrap=True,
    )
    gap = TOWN_DOT
    if town.label_side == "right":
        label = ft.Container(text, left=x + gap, top=y - 8)
    elif town.label_side == "left":
        label = ft.Container(text, right=island.MAP_WIDTH - x + gap, top=y - 8)
    elif town.label_side == "below_left":
        label = ft.Container(text, right=island.MAP_WIDTH - x + 2, top=y + gap)
    else:  # "above" / "below": centred on the dot
        top = y - 20 if town.label_side == "above" else y + 4
        label = ft.Container(text, left=x - TOWN_LABEL_WIDTH / 2, top=top, width=TOWN_LABEL_WIDTH,
                             alignment=ft.Alignment.TOP_CENTER)
    return [dot, label]


def _legend(app: "GialosApp") -> ft.Row:
    state = app.state

    def item(color: str, text: str) -> ft.Row:
        dot = ft.Container(width=12, height=12, shape=ft.BoxShape.CIRCLE, bgcolor=color)
        return ft.Row([dot, ft.Text(text, style=theme.CAPTION, color=theme.INK_80)], spacing=6, tight=True)

    items = [item(c, state.t("level_" + lvl)) for lvl, c in theme.CLARITY_COLORS.items()]
    items.append(item(theme.ACCENT_DEEP, state.t("legend_match")))
    return ft.Row(items, spacing=theme.S3, run_spacing=theme.S2, wrap=True)


def _match_card(app: "GialosApp", beach_id: str) -> ft.Container:
    state = app.state
    beach = get_beach(beach_id)
    return ft.Container(
        content=ft.Row(
            [
                ft.Container(
                    content=ft.Image(src=beach_image_src(beach_id), fit=ft.BoxFit.COVER),
                    width=56,
                    height=56,
                    border_radius=theme.RADIUS_SMALL,
                    clip_behavior=ft.ClipBehavior.ANTI_ALIAS,
                ),
                ft.Column(
                    [
                        ft.Text(state.t("your_match_card"), style=theme.LABEL, color=theme.ACCENT),
                        ft.Text(beach.name[state.language], style=theme.BODY_STRONG),
                    ],
                    spacing=2,
                    expand=True,
                ),
                ft.Icon(ft.Icons.ARROW_FORWARD_IOS, size=16, color=theme.INK_60),
            ],
            spacing=theme.S3,
        ),
        bgcolor=theme.SURFACE,
        border_radius=theme.RADIUS,
        padding=12,
        shadow=theme.soft_shadow(),
        ink=True,
        on_click=lambda _: app.open_beach(beach_id),
    )


def build(app: "GialosApp") -> ft.Control:
    state = app.state
    match_id = app.recommendation().beach_id
    # Only beaches with a real photo get a pin; the user's match is always shown
    # (drawn last so it sits on top of nearby pins).
    pins = [_pin(app, b.id, False) for b in BEACHES if b.id != match_id and has_photo(b.id)]
    pins.append(_pin(app, match_id, True))
    towns = [c for town in island.TOWNS for c in _town(app, town)]
    credit = ft.Container(
        ft.Text(state.t("osm_credit"), size=9, color=theme.WHITE_80),
        left=12, bottom=8,
    )
    island_map = ft.Container(
        content=ft.Stack(
            [
                ft.Image(src=ISLAND_IMAGE, width=island.MAP_WIDTH, height=island.MAP_HEIGHT, fit=ft.BoxFit.FILL),
                *towns,
                *pins,
                credit,
            ],
            width=island.MAP_WIDTH,
            height=island.MAP_HEIGHT,
        ),
        border_radius=theme.RADIUS,
        shadow=theme.soft_shadow(),
    )
    day_word = state.t("day_lower_" + state.preferences.day)
    return ft.ListView(
        [
            ft.Text(state.t("map_title"), style=theme.DISPLAY),
            ft.Text(state.t("map_hint", day=day_word), style=theme.BODY),
            ft.Container(height=theme.S1),
            ft.Row([island_map], alignment=ft.MainAxisAlignment.CENTER),
            _legend(app),
            _match_card(app, match_id),
            ft.Text(state.t("mock_data_note"), style=theme.CAPTION, text_align=ft.TextAlign.CENTER),
        ],
        key="map",
        spacing=theme.S3,
        padding=ft.Padding.only(left=theme.S4, right=theme.S4, top=theme.S2, bottom=theme.S4),
        expand=True,
    )
